class TestRequirementsTxt:
    """Service deps split into floors and a lock (ADR-0012):
    requirements.in declares the four service-direct floors (fastapi, uvicorn,
    python-ldap, pyyaml) — data-layer deps belong to naas_shared and must NOT be
    duplicated there. requirements.txt is the pip-compiled lock; it deliberately
    pins the FULL transitive closure (including shared's sqlalchemy/asyncpg/redis)
    so the image install is reproducible. The Dockerfile installs the lock, then
    naas_shared editable with --no-deps.
    """

    def test_requirements_in_exists(self) -> None:
        """requirements.in (the declared floors) must exist.

        WHY: It is the pip-compile input; the lock is generated from it. Without it
        the lock cannot be regenerated when a floor changes.
        """
        assert REQUIREMENTS_IN_PATH.exists(), (
            f"requirements.in not found at {REQUIREMENTS_IN_PATH}. "
            "The service's declared dependency floors live here."
        )

    def test_requirements_txt_exists(self) -> None:
        """requirements.txt (the lock) must exist at services/identity-normalization/.

        WHY: The Dockerfile copies this file and runs `pip install -r` on it.
        Without it, the image build fails at the COPY/RUN step.
        """
        assert REQUIREMENTS_PATH.exists(), (
            f"requirements.txt not found at {REQUIREMENTS_PATH}. "
            "Regenerate the lock from requirements.in — see "
            "DEPENDENCIES.md."
        )

    def test_requirements_txt_is_compiled_lock(self) -> None:
        """requirements.txt must be a pip-compiled lock, not a hand-edited list.

        WHY: ADR-0012 requires the install artifact to be the generated lock. The
        pip-compile header marks it as such and records the regenerate command.
        """
        assert "autogenerated by pip-compile" in _requirements_text(), (
            "requirements.txt must be generated by pip-compile (its header should "
            "say so). Regenerate it from requirements.in + shared/pyproject.toml — "
            "see DEPENDENCIES.md."
        )

    def test_requirements_in_lists_fastapi(self) -> None:
        """requirements.in must declare fastapi (any version specifier or bare name).

        WHY: fastapi is the web framework for the /health endpoint; it is a
        service-direct dependency and must be declared in the floors, not relied on
        transitively. Spec §5.8 names it explicitly.
        """
        lines = _requirements_in_lines()
        fastapi_lines = [line for line in lines if line.startswith("fastapi")]
        assert fastapi_lines, (
            f"requirements.in must list 'fastapi' (with or without version pin). "
            f"Found lines: {lines}"
        )

    def test_requirements_in_lists_uvicorn(self) -> None:
        """requirements.in must declare uvicorn (with or without [standard] extra).

        WHY: uvicorn is the ASGI server. The Dockerfile CMD is 'uvicorn app.main:app
        --port 8002'. If uvicorn is absent from the floors the lock won't pin it and
        the CMD fails with 'command not found'.
        """
        lines = _requirements_in_lines()
        uvicorn_lines = [line for line in lines if line.startswith("uvicorn")]
        assert uvicorn_lines, (
            f"requirements.in must list 'uvicorn' (with or without [standard]). "
            f"Found lines: {lines}"
        )

    def test_requirements_in_lists_python_ldap(self) -> None:
        """requirements.in must declare python-ldap (required for LDAP enrichment).

        WHY: Spec §5.8 — 'python-ldap>=3.4'. python-ldap is the C-extension LDAP
        client used by the LdapEnricher adapter (app/adapters/ldap.py). It is
        service-specific (not a shared dep), so the floor must declare it.
        Note: PyPI name is 'python-ldap'; pip normalizes hyphens to dashes/underscores.
        """
        lines = _requirements_in_lines()
        # Match 'python-ldap', 'python_ldap' — pip normalizes these
        ldap_lines = [
            line
            for line in lines
            if line.startswith("python-ldap") or line.startswith("python_ldap")
        ]
        assert ldap_lines, (
            f"requirements.in must list 'python-ldap' (with or without version pin). "
            f"Spec §5.8. Found lines: {lines}"
        )

    def test_requirements_in_lists_pyyaml(self) -> None:
        """requirements.in must declare pyyaml (required for loading normalization.yaml).

        WHY: Spec §5.8 — 'pyyaml>=6.0'. The composition root loads and validates
        config/normalization.yaml at startup. Without pyyaml in the floors the lock
        won't pin it and the yaml.safe_load call raises ModuleNotFoundError.
        """
        lines = _requirements_in_lines()
        # Match 'pyyaml', 'pyyaml>=...', etc.
        yaml_lines = [line for line in lines if line.startswith("pyyaml")]
        assert yaml_lines, (
            f"requirements.in must list 'pyyaml' (with or without version pin). "
            f"Spec §5.8. Found lines: {lines}"
        )

    def test_requirements_in_does_not_list_sqlalchemy(self) -> None:
        """requirements.in must NOT list sqlalchemy.

        WHY: Data-layer dependencies are owned by naas_shared (shared/pyproject.toml).
        Declaring them in the service floors would create two sources of truth. They
        legitimately appear in the generated lock as part of shared's transitive
        closure — but not as a service-declared floor.
        """
        lines = _requirements_in_lines()
        sqlalchemy_lines = [line for line in lines if line.startswith("sqlalchemy")]
        assert not sqlalchemy_lines, (
            f"requirements.in must NOT declare 'sqlalchemy' — it is owned by "
            f"naas_shared. Found: {sqlalchemy_lines}"
        )

    def test_requirements_in_does_not_list_asyncpg(self) -> None:
        """requirements.in must NOT list asyncpg.

        WHY: asyncpg is the async PostgreSQL driver owned by naas_shared's
        sqlalchemy[asyncio] dependency. Declaring it in the service floors would
        duplicate the source of truth (see sqlalchemy above).
        """
        lines = _requirements_in_lines()
        asyncpg_lines = [line for line in lines if line.startswith("asyncpg")]
        assert not asyncpg_lines, (
            f"requirements.in must NOT declare 'asyncpg' — it is owned by "
            f"naas_shared. Found: {asyncpg_lines}"
        )

    def test_requirements_in_does_not_list_redis_client(self) -> None:
        """requirements.in must NOT list the redis Python client package.

        WHY: redis-py is owned by naas_shared. Declaring it in the service floors
        would duplicate the source of truth.
        """
        lines = _requirements_in_lines()
        redis_lines = [
            line
            for line in lines
            if line == "redis"
            or line.startswith("redis==")
            or line.startswith("redis>=")
            or line.startswith("redis~=")
        ]
        assert not redis_lines, (
            f"requirements.in must NOT declare 'redis' — it is owned by "
            f"naas_shared. Found: {redis_lines}"
        )


